import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { RealEngineHarness } from "./realEngineHarness";
import { SceneType, FactionType } from "@/types";

// Real engine, real game-logic services — only PixiJS is stubbed (the comprehensive
// headless stub so the real scenes construct without a GPU).
vi.mock("pixi.js", async () => (await import("./pixiStub")).makePixiStub());

describe("RealEngineHarness — real-engine playtest driver", () => {
  let harness: RealEngineHarness;

  beforeEach(() => {
    localStorage.clear();
  });

  afterEach(() => {
    harness?.dispose();
    vi.clearAllMocks();
    localStorage.clear();
  });

  it("boots a real game to the main menu with no errors", async () => {
    harness = await RealEngineHarness.boot();

    expect(harness.engine).toBeDefined();
    // A real galaxy was generated by the real GalaxyService.
    expect(harness.galaxy()).not.toBeNull();
    expect(harness.galaxy()!.systems.length).toBeGreaterThan(0);
    expect(harness.currentSceneType()).toBe(SceneType.MAIN_MENU);
    expect(harness.currentScene()).not.toBeNull();
    // Clean boot ⇒ nothing logged/thrown.
    expect(harness.errors()).toEqual([]);
  });

  it("starts a fresh game: real player + loadout + banking, no errors", async () => {
    harness = await RealEngineHarness.boot();

    await harness.newGame(FactionType.OUTLANDERS);

    const player = harness.player();
    expect(player).not.toBeNull();
    expect(player!.faction).toBe(FactionType.OUTLANDERS);
    expect(player!.currentSystemId).toBeTruthy();
    // credits() is the АБС current-account projection — seeded for a new player.
    expect(harness.credits()).toBeGreaterThan(0);
    expect(harness.errors()).toEqual([]);
  });

  it("transitions between scenes through the real engine without throwing", async () => {
    harness = await RealEngineHarness.boot();
    await harness.newGame();

    await harness.goTo(SceneType.STAR_MAP);
    expect(harness.currentSceneType()).toBe(SceneType.STAR_MAP);

    await harness.goTo(SceneType.SPACE_FLIGHT);
    expect(harness.currentSceneType()).toBe(SceneType.SPACE_FLIGHT);

    expect(harness.errors()).toEqual([]);
  });

  it("advancing a frame on the current scene does not throw", async () => {
    harness = await RealEngineHarness.boot();
    await harness.newGame();

    harness.tick(16);
    harness.tick(16);

    expect(harness.errors()).toEqual([]);
  });

  it("exposes real quest + galaxy services on a fresh game", async () => {
    harness = await RealEngineHarness.boot();
    await harness.newGame();

    // The real QuestManager is reachable (no active quests on a brand-new game).
    expect(harness.quests().getActiveQuests()).toEqual([]);
    expect(harness.galaxy()!.systems.length).toBeGreaterThan(0);
  });
});
